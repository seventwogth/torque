use std::path::PathBuf;

use torque_bridges::{BridgeLine, required_transports};
use torque_router::RoutingMode;

use crate::paths::{Layout, torrc_path};

/// A pluggable-transport helper binary and the transports it provides.
///
/// One binary serves several transports — `lyrebird` alone covers obfs4,
/// meek_lite and webtunnel — which is why this is not a per-transport map.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TransportPlugin {
    pub transports: Vec<String>,
    pub executable: PathBuf,
    pub args: Vec<String>,
}

impl TransportPlugin {
    /// The transports shipped in the Tor Expert Bundle.
    pub fn expert_bundle(layout: &Layout) -> Vec<Self> {
        vec![
            Self {
                transports: ["obfs4", "meek_lite", "webtunnel"]
                    .map(str::to_owned)
                    .to_vec(),
                executable: layout.vendor_binary("lyrebird"),
                args: Vec::new(),
            },
            Self {
                transports: vec!["snowflake".to_owned()],
                executable: layout.vendor_binary("snowflake-client"),
                args: Vec::new(),
            },
            Self {
                transports: vec!["conjure".to_owned()],
                executable: layout.vendor_binary("conjure-client"),
                args: Vec::new(),
            },
        ]
    }

    /// The value of a `ClientTransportPlugin` option, without the option name,
    /// so the same rendering serves torrc and `SETCONF`.
    pub fn transport_plugin_value(&self) -> String {
        let mut value = format!(
            "{} exec {}",
            self.transports.join(","),
            torrc_path(&self.executable)
        );
        for arg in &self.args {
            value.push(' ');
            value.push_str(arg);
        }
        value
    }

    fn render(&self) -> String {
        format!("ClientTransportPlugin {}", self.transport_plugin_value())
    }
}

/// Everything that goes into the generated torrc.
#[derive(Debug, Clone)]
pub struct TorConfig {
    pub socks_port: u16,
    pub dns_port: u16,
    /// Tor's native transparent proxy port. Unsupported on Windows, where the
    /// Wintun backend hands flows to `socks_port` instead.
    pub trans_port: Option<u16>,
    pub routing: RoutingMode,
    pub bridges: Vec<BridgeLine>,
    pub plugins: Vec<TransportPlugin>,
    /// Extra raw torrc lines from the user, appended last so they win.
    pub extra_lines: Vec<String>,
}

impl TorConfig {
    pub fn new(routing: RoutingMode) -> Self {
        Self {
            socks_port: 9050,
            dns_port: 9053,
            trans_port: if cfg!(windows) { None } else { Some(9040) },
            routing,
            bridges: Vec::new(),
            plugins: Vec::new(),
            extra_lines: Vec::new(),
        }
    }

    pub fn with_bridges(mut self, bridges: Vec<BridgeLine>) -> Self {
        self.bridges = bridges;
        self
    }

    /// Keeps only the plugins some configured bridge actually needs, so we do
    /// not require a `snowflake-client` binary for an obfs4-only setup.
    pub fn needed_plugins(&self) -> Vec<&TransportPlugin> {
        let needed = required_transports(&self.bridges);
        self.plugins
            .iter()
            .filter(|plugin| {
                plugin
                    .transports
                    .iter()
                    .any(|transport| needed.contains(transport))
            })
            .collect()
    }

    /// The `SETCONF` pairs that switch a running tor onto this bridge set.
    ///
    /// Empty when there are no bridges — the caller should `RESETCONF`
    /// [`Self::BRIDGE_KEYS`] instead, since an empty `Bridge` list with
    /// `UseBridges 1` is rejected.
    ///
    /// Repeating `Bridge` is deliberate: that is how tor takes a list. One
    /// `SETCONF` is atomic, so `UseBridges` and the bridges it requires are
    /// sent together and tor never sees the invalid intermediate state.
    pub fn bridge_settings(&self) -> Vec<(String, String)> {
        if self.bridges.is_empty() {
            return Vec::new();
        }

        let mut settings = vec![("UseBridges".to_owned(), "1".to_owned())];
        for plugin in self.needed_plugins() {
            settings.push((
                "ClientTransportPlugin".to_owned(),
                plugin.transport_plugin_value(),
            ));
        }
        for bridge in &self.bridges {
            settings.push(("Bridge".to_owned(), bridge.to_bridge_value()));
        }
        settings
    }

    /// Options to reset when turning bridges off.
    pub const BRIDGE_KEYS: [&'static str; 3] = ["UseBridges", "Bridge", "ClientTransportPlugin"];

    pub fn render(&self, layout: &Layout) -> String {
        let mut lines = vec![
            "# Generated by Torque. Edits are overwritten on every start.".to_owned(),
            format!("DataDirectory {}", torrc_path(&layout.data_dir)),
            // `auto` plus the port file: no fixed control port to collide with
            // a system tor or Tor Browser.
            "ControlPort auto".to_owned(),
            format!(
                "ControlPortWriteToFile {}",
                torrc_path(&layout.control_port_file())
            ),
            "CookieAuthentication 1".to_owned(),
            format!("SocksPort {}", self.socks_port),
            "Log notice stdout".to_owned(),
        ];

        if layout.geoip().exists() {
            lines.push(format!("GeoIPFile {}", torrc_path(&layout.geoip())));
        }
        if layout.geoip6().exists() {
            lines.push(format!("GeoIPv6File {}", torrc_path(&layout.geoip6())));
        }

        if self.routing == RoutingMode::Transparent {
            lines.push(String::new());
            lines.push("# Transparent mode: Tor carries no UDP, so DNS has to".to_owned());
            lines.push("# terminate here, and .onion names only resolve because".to_owned());
            lines.push("# AutomapHostsOnResolve hands back a virtual address.".to_owned());
            lines.push(format!("DNSPort {}", self.dns_port));
            lines.push("AutomapHostsOnResolve 1".to_owned());
            lines.push("VirtualAddrNetworkIPv4 10.192.0.0/10".to_owned());
            if let Some(port) = self.trans_port {
                lines.push(format!("TransPort {port}"));
            }
        }

        if !self.bridges.is_empty() {
            lines.push(String::new());
            lines.push("UseBridges 1".to_owned());
            for plugin in self.needed_plugins() {
                lines.push(plugin.render());
            }
            for bridge in &self.bridges {
                lines.push(format!("Bridge {bridge}"));
            }
        }

        if !self.extra_lines.is_empty() {
            lines.push(String::new());
            lines.push("# User additions".to_owned());
            lines.extend(self.extra_lines.iter().cloned());
        }

        let mut rendered = lines.join("\n");
        rendered.push('\n');
        rendered
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const FINGERPRINT: &str = "0123456789ABCDEF0123456789ABCDEF01234567";

    fn layout() -> Layout {
        Layout {
            data_dir: PathBuf::from("/state/tor"),
            vendor_dir: PathBuf::from("/app/vendor"),
        }
    }

    #[test]
    fn renders_proxy_only_without_transparent_options() {
        let rendered = TorConfig::new(RoutingMode::ProxyOnly).render(&layout());
        assert!(rendered.contains("SocksPort 9050"));
        assert!(rendered.contains("ControlPort auto"));
        assert!(rendered.contains("CookieAuthentication 1"));
        assert!(!rendered.contains("AutomapHostsOnResolve"));
        assert!(!rendered.contains("DNSPort"));
    }

    #[test]
    fn transparent_mode_adds_dns_and_automap() {
        let rendered = TorConfig::new(RoutingMode::Transparent).render(&layout());
        assert!(rendered.contains("DNSPort 9053"));
        assert!(rendered.contains("AutomapHostsOnResolve 1"));
        assert!(rendered.contains("VirtualAddrNetworkIPv4 10.192.0.0/10"));
        // TransPort exists everywhere except Windows.
        assert_eq!(rendered.contains("TransPort 9040"), !cfg!(windows));
    }

    #[test]
    fn selects_only_the_plugins_configured_bridges_need() {
        let layout = layout();
        let bridge: BridgeLine = format!("obfs4 192.0.2.1:443 {FINGERPRINT} cert=x iat-mode=0")
            .parse()
            .expect("valid bridge");
        let mut config = TorConfig::new(RoutingMode::ProxyOnly).with_bridges(vec![bridge]);
        config.plugins = TransportPlugin::expert_bundle(&layout);

        let selected = config.needed_plugins();
        assert_eq!(selected.len(), 1);
        assert!(selected[0].transports.contains(&"obfs4".to_owned()));

        let rendered = config.render(&layout);
        assert!(rendered.contains("UseBridges 1"));
        assert!(rendered.contains("ClientTransportPlugin obfs4,meek_lite,webtunnel exec"));
        assert!(!rendered.contains("snowflake"));
        assert!(rendered.contains(&format!("Bridge obfs4 192.0.2.1:443 {FINGERPRINT}")));
    }

    #[test]
    fn vanilla_bridges_need_no_plugin() {
        let layout = layout();
        let bridge: BridgeLine = format!("192.0.2.7:9001 {FINGERPRINT}")
            .parse()
            .expect("valid bridge");
        let mut config = TorConfig::new(RoutingMode::ProxyOnly).with_bridges(vec![bridge]);
        config.plugins = TransportPlugin::expert_bundle(&layout);

        assert!(config.needed_plugins().is_empty());
        let rendered = config.render(&layout);
        assert!(rendered.contains("UseBridges 1"));
        assert!(!rendered.contains("ClientTransportPlugin"));
    }

    #[test]
    fn bridge_settings_repeat_the_bridge_key() {
        let layout = layout();
        let (bridges, errors) = torque_bridges::parse_many(&format!(
            "obfs4 192.0.2.1:443 {FINGERPRINT} cert=x iat-mode=0\n\
             obfs4 192.0.2.2:443 {FINGERPRINT} cert=y iat-mode=0\n"
        ));
        assert!(errors.is_empty());

        let mut config = TorConfig::new(RoutingMode::ProxyOnly).with_bridges(bridges);
        config.plugins = TransportPlugin::expert_bundle(&layout);
        let settings = config.bridge_settings();

        assert_eq!(settings[0], ("UseBridges".to_owned(), "1".to_owned()));
        assert_eq!(
            settings
                .iter()
                .filter(|(key, _)| key == "Bridge")
                .count(),
            2
        );
        let plugins: Vec<_> = settings
            .iter()
            .filter(|(key, _)| key == "ClientTransportPlugin")
            .collect();
        assert_eq!(plugins.len(), 1);
        assert!(plugins[0].1.starts_with("obfs4,meek_lite,webtunnel exec "));
    }

    #[test]
    fn vanilla_bridges_need_no_transport_plugin_setting() {
        let layout = layout();
        let bridge: BridgeLine = format!("192.0.2.7:9001 {FINGERPRINT}")
            .parse()
            .expect("valid bridge");
        let mut config = TorConfig::new(RoutingMode::ProxyOnly).with_bridges(vec![bridge]);
        config.plugins = TransportPlugin::expert_bundle(&layout);

        let settings = config.bridge_settings();
        assert!(!settings.iter().any(|(key, _)| key == "ClientTransportPlugin"));
        assert_eq!(settings.iter().filter(|(key, _)| key == "Bridge").count(), 1);
    }

    #[test]
    fn no_bridges_means_reset_not_an_empty_list() {
        // UseBridges 1 with an empty Bridge list is rejected by tor, so the
        // caller has to RESETCONF instead of sending nothing.
        assert!(
            TorConfig::new(RoutingMode::ProxyOnly)
                .bridge_settings()
                .is_empty()
        );
        assert!(TorConfig::BRIDGE_KEYS.contains(&"UseBridges"));
    }

    #[test]
    fn user_additions_come_last() {
        let mut config = TorConfig::new(RoutingMode::ProxyOnly);
        config.extra_lines = vec!["ExcludeExitNodes {ru}".to_owned()];
        let rendered = config.render(&layout());
        let tail = rendered.lines().last().expect("non-empty torrc");
        assert_eq!(tail, "ExcludeExitNodes {ru}");
    }
}
